export const getSignVideo = (signOrId) => {
  if (!signOrId) return defaultGrokVideo;
  if (typeof signOrId === 'object') {
    return SIGN_VIDEOS[signOrId.sign] || SIGN_VIDEOS[signOrId.id] || defaultGrokVideo;
  }
  return SIGN_VIDEOS[signOrId] || SIGN_VIDEOS[signOrId.toUpperCase()] || defaultGrokVideo;
};
